#!/usr/bin/env python3
"""Generate src/vanArt.ts, the camper drawings as data for react-native-svg.

The drawings come from van_drawings.py (SVG in centimetres). Each view
becomes a list of shapes; the body colour is a placeholder the app fills
with the user's colour, and the ground shadow is kept apart so it does not
tilt with the van.

Usage:
  python3 scripts/make_van_art.py           # rewrite src/vanArt.ts
  python3 scripts/make_van_art.py --check   # exit 1 if src/vanArt.ts is stale
"""

import json
import pathlib
import sys
import xml.etree.ElementTree as ET

import van_drawings as drawings

TARGET = pathlib.Path(__file__).resolve().parents[1] / "src" / "vanArt.ts"
BODY = "#a1b2c3"  # Placeholder for the body colour; not used anywhere else.


def number(value):
    v = float(value)
    return int(v) if v == int(v) else round(v, 2)


def shapes(svg):
    """Turn an SVG fragment into a list of plain shape objects."""
    out = []
    for el in ET.fromstring("<g>%s</g>" % svg):
        a = el.attrib
        shape = {"t": el.tag}
        if el.tag == "path":
            shape["d"] = a["d"]
        elif el.tag == "rect":
            for k in ("x", "y", "width", "height", "rx"):
                shape[{"width": "w", "height": "h"}.get(k, k)] = number(a.get(k, 0))
        elif el.tag == "circle":
            for k in ("cx", "cy", "r"):
                shape[k] = number(a[k])
        elif el.tag == "ellipse":
            for k in ("cx", "cy", "rx", "ry"):
                shape[k] = number(a[k])
        else:
            raise ValueError("unsupported element %s" % el.tag)
        fill = a.get("fill", "#000")
        if fill.lower() == BODY:
            shape["body"] = True
        else:
            shape["fill"] = fill
        if "stroke" in a:
            shape["stroke"] = a["stroke"]
            shape["sw"] = number(a.get("stroke-width", 1))
        if a.get("stroke-linecap") == "round":
            shape["lc"] = "round"
        if "opacity" in a:
            shape["op"] = number(a["opacity"])
        out.append(shape)
    return out


def split_shadow(items):
    shadow = [s for s in items if s.get("fill") == "url(#shadow)"]
    return [s for s in items if s.get("fill") != "url(#shadow)"], (shadow[0] if shadow else None)


def gradients():
    out = []
    for el in ET.fromstring("<defs>%s</defs>" % drawings.DEFS):
        g = {"kind": "linear" if el.tag == "linearGradient" else "radial", "id": el.attrib["id"]}
        for k in ("x1", "y1", "x2", "y2", "cx", "cy", "r"):
            if k in el.attrib:
                g[k] = number(el.attrib[k])
        g["stops"] = [
            [number(s.attrib["offset"]), s.attrib["stop-color"], number(s.attrib.get("stop-opacity", 1))]
            for s in el
        ]
        out.append(g)
    return out


def build():
    art = {}
    for kind in drawings.TYPES:
        side, _ = drawings.SIDES[kind](BODY)
        rear, _, _ = drawings.rear_view(BODY, kind)
        top, _, _ = drawings.top_view(BODY, kind)
        side_shapes, side_shadow = split_shadow(shapes(side))
        rear_shapes, rear_shadow = split_shadow(shapes(rear))
        art[kind] = {
            "meta": drawings.META[kind],
            "side": side_shapes,
            "sideShadow": side_shadow,
            "rear": rear_shapes,
            "rearShadow": rear_shadow,
            "top": shapes(top),
        }
    lines = [
        "/**",
        " * Camper drawings as data. Generated by scripts/make_van_art.py from",
        " * scripts/van_drawings.py; do not edit. Units are centimetres: side views",
        " * run from the rear (x = 0) to the front, rear views are centred on x = 0,",
        " * top views have the front at y = 0; the ground is y = 0 and up is negative.",
        " */",
        "",
        "import type { ArtGradient, CamperArt } from './vanArtTypes';",
        "",
        "export const ART_GRADIENTS: ArtGradient[] = %s;" % json.dumps(gradients(), separators=(",", ":")),
        "",
        "export const VAN_ART: Record<string, CamperArt> = {",
    ]
    for kind in drawings.TYPES:
        lines.append("  %s: %s," % (kind, json.dumps(art[kind], separators=(",", ":"))))
    lines += ["};", ""]
    return "\n".join(lines)


def main(args):
    text = build()
    if "--check" in args:
        if not TARGET.exists() or TARGET.read_text() != text:
            print("src/vanArt.ts is out of date; run python3 scripts/make_van_art.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    print("Wrote %s (%d KB)" % (TARGET.relative_to(TARGET.parents[1]), len(text) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
