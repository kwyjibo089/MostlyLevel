"""The campervan seen from behind and from the right, drawn tilted.

The shapes come from src/van_shapes.py, generated by tools/make_vans.py (a
Fiat Ducato-style panel-van campervan, no logo). draw_tilted() rotates their
points about the lower wheel's ground contact, so the van pivots on the
wheel that stays down, and fills them with framebuf.poly() and ellipse()
into a reusable 4-bit Bitmap. Points are quarter pixels and the rotation is
integer maths: on the board every float result is a new heap object.
"""

import math
import sys
from array import array

from compositor import Bitmap

POLY, OUTLINE, LINE, DISC = 0, 1, 2, 3


def _load():
    import van_shapes

    views = {}
    for name in ("SIDE", "REAR"):
        points = getattr(van_shapes, name + "_POINTS")
        shapes = getattr(van_shapes, name + "_SHAPES")
        views[name] = {
            "ground": getattr(van_shapes, name + "_GROUND"),
            "wheels": getattr(van_shapes, name + "_WHEELS"),
            "points": array("h", points),
            "shapes": shapes,
            # Rotated points in whole pixels, reused for every tilt.
            "rotated": array("h", bytes(2 * len(points))),
            "max_radius": max([shape[4] for shape in shapes] + [0]),
        }
    colours = list(van_shapes.COLOURS)
    # The tables were copied into arrays; drop the module to free them.
    sys.modules.pop("van_shapes", None)
    return views, colours


_views, COLOURS = _load()
SIDE = _views["SIDE"]
REAR = _views["REAR"]
del _views

def _rotate(van, angle_deg):
    """Rotate the view's points about the lower wheel into van["rotated"].

    Positive angles turn clockwise on screen: the right side goes down, so
    the van pivots on its right wheel; negative angles pivot on the left.
    Returns the bounds (left, top, width, height) in whole pixels.
    """
    left_wheel, right_wheel = van["wheels"]
    pivot_x = right_wheel if angle_deg > 0 else left_wheel
    pivot_y = van["ground"]
    angle = math.radians(angle_deg)
    cos_a = int(math.cos(angle) * 1024)
    sin_a = int(math.sin(angle) * 1024)
    source = van["points"]
    rotated = van["rotated"]
    min_x = min_y = 32767
    max_x = max_y = -32768
    for index in range(0, len(source), 2):
        dx = source[index] - pivot_x
        dy = source[index + 1] - pivot_y
        # Quarter pixels back to whole pixels, rounded.
        x = (pivot_x + ((dx * cos_a - dy * sin_a) >> 10) + 2) >> 2
        y = (pivot_y + ((dx * sin_a + dy * cos_a) >> 10) + 2) >> 2
        rotated[index] = x
        rotated[index + 1] = y
        if x < min_x:
            min_x = x
        if x > max_x:
            max_x = x
        if y < min_y:
            min_y = y
        if y > max_y:
            max_y = y
    margin = van["max_radius"] + 1
    left = min_x - margin
    top = min_y - margin
    return left, top, max_x + margin - left + 1, max_y + margin - top + 1


# Reused pixel buffers, sized on first use for the largest tilt, and the
# last picture drawn into each: (angle, picture, x, y).
_buffers = {}
_last = {}


def _buffer(van, max_angle):
    key = id(van)
    if key not in _buffers:
        size = 0
        step = max(1, int(max_angle) // 8)
        for angle in range(-int(max_angle) - 1, int(max_angle) + 2, step):
            _, _, width, height = _rotate(van, angle)
            size = max(size, (width + 1) // 2 * height)
        for angle in (-max_angle, max_angle):
            _, _, width, height = _rotate(van, angle)
            size = max(size, (width + 1) // 2 * height)
        _buffers[key] = bytearray(size + 64)  # Margin for rounding.
    return _buffers[key]


def draw_tilted(van, angle_deg, max_angle):
    """Draw `van` tilted by `angle_deg` (clamped to ±max_angle).

    Returns (picture, x, y): a new Bitmap and its top-left corner relative
    to the point midway between the wheels on the ground.
    """
    angle_deg = max(-max_angle, min(max_angle, angle_deg))
    last = _last.get(id(van))
    if last is not None and last[0] == angle_deg:
        # Same tilt: the buffer still holds this picture. Returning the same
        # object lets the compositor skip strips that did not change.
        return last[1:]
    buffer = _buffer(van, max_angle)
    left, top, width, height = _rotate(van, angle_deg)
    picture = Bitmap(width, height, COLOURS, buffer=buffer)
    target = picture.framebuffer
    target.fill(0)
    rotated = van["rotated"]
    points = memoryview(rotated)
    for kind, value, start, count, radius in van["shapes"]:
        index = 2 * start
        if kind == DISC:
            target.ellipse(
                rotated[index] - left, rotated[index + 1] - top, radius, radius, value, True
            )
        elif kind == LINE:
            target.line(
                rotated[index] - left, rotated[index + 1] - top,
                rotated[index + 2] - left, rotated[index + 3] - top, value,
            )
        else:
            target.poly(-left, -top, points[index:index + 2 * count], value, kind == POLY)
    wheel_left, wheel_right = van["wheels"]
    origin_x = (wheel_left + wheel_right) // 2  # Quarter pixels.
    result = (
        picture,
        left - ((origin_x + 2) >> 2),
        top - (van["ground"] >> 2),  # As before: 37.5 px rounds to 37.
    )
    _last[id(van)] = (angle_deg,) + result
    return result
