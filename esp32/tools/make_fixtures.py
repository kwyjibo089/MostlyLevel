#!/usr/bin/env python3
"""Generate shared/fixtures/*.json, reference results of the ESP32 app's logic.

The MicroPython sources in src/ are run under CPython with the test fakes
(tests/fakes), and their results for a fixed set of inputs are written as
JSON. The mobile app's tests check its own implementation against these
files, so both apps decode sensor packets and compute levelling the same way.

Usage:
  tools/make_fixtures.py           # rewrite shared/fixtures/*.json
  tools/make_fixtures.py --check   # exit 1 if a fixture file is stale
"""

import json
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT.parent / "shared" / "fixtures"
sys.path[:0] = [str(ROOT / "tests" / "fakes"), str(ROOT / "src"), str(ROOT / "tests")]

from support import clock  # noqa: E402

clock.install()

import app  # noqa: E402
import ble_read  # noqa: E402
import config  # noqa: E402

GENERATED_BY = "Generated by esp32/tools/make_fixtures.py from esp32/src; do not edit."


def attitude_packet(raw):
    """A 20-byte 55 61 notification carrying nine signed 16-bit values."""
    return bytes((config.SENSOR_PACKET_HEADER, config.SENSOR_ATTITUDE_PACKET_TYPE)) + struct.pack(
        "<9h", *raw
    )


def rounded(values, digits=6):
    return {key: round(value, digits) for key, value in values.items()}


def sensor_fixture():
    packets = []
    raws = [
        (0, 0, 2048, 0, 0, 0, 0, 0, 0),
        (120, -340, 2030, 15, -8, 3, 182, -273, 16384),
        (-32768, 32767, -1, 1, -1, 32767, -32768, 32767, -16384),
        (512, 0, 2048, 0, 0, 0, -1092, 546, -5461),
    ]
    for raw in raws:
        packet = attitude_packet(raw)
        packets.append({"hex": packet.hex(), "decoded": rounded(ble_read.decode_packet(packet))})
    good = attitude_packet(raws[1])
    invalid = [
        good[:19],  # Too short.
        good + b"\x00",  # Too long.
        b"\x54" + good[1:],  # Wrong header.
        good[:1] + b"\x71" + good[2:],  # Register response, not attitude.
    ]
    for packet in invalid:
        packets.append({"hex": packet.hex(), "decoded": None})

    # Notifications as received, split into frames like the client does.
    power = bytes.fromhex("55716400810100000000000000000000e8030000")
    notifications = [
        good,
        power + good,
        good + power,
        good + power + good,
        good + b"\x55",
        good + b"\x00" + good[1:],
        good[:7],
    ]
    split = [
        {"hex": packet.hex(), "frames": [frame.hex() for frame in ble_read.split_frames(packet)]}
        for packet in notifications
    ]

    battery_raw = [
        400, 397, 396, 393, 387, 385, 382, 379, 377, 373, 370, 368, 351, 350, 340, 339, 0,
    ]
    return {
        "_comment": GENERATED_BY,
        "attitude_packets": packets,
        # The owner's sensor answered 55 71 64 00 81 01 ...: raw 385 = 3.85 V = 60 %.
        "power_read_command": config.SENSOR_POWER_READ_COMMAND.hex(),
        "power_response": {
            "hex": "55716400810100000000000000000000e8030000",
            "raw": 385,
            "percent": ble_read.battery_percent(385),
        },
        "battery_percent": [[raw, ble_read.battery_percent(raw)] for raw in battery_raw],
        "notifications": split,
    }


def levelling_fixture():
    cases = []
    inputs = [
        # Sensor channels as decoded, then the stored level reference.
        ({"roll": 0.0, "pitch": 0.0}, (0.0, 0.0)),
        ({"roll": 2.0, "pitch": 0.0}, (0.0, 0.0)),
        ({"roll": -1.5, "pitch": 0.0}, (0.0, 0.0)),
        ({"roll": 0.0, "pitch": 1.2}, (0.0, 0.0)),
        ({"roll": 0.0, "pitch": -2.4}, (0.0, 0.0)),
        ({"roll": 1.3, "pitch": -0.7}, (0.0, 0.0)),
        ({"roll": -3.1, "pitch": 2.2}, (0.0, 0.0)),
        ({"roll": 0.2, "pitch": 0.1}, (0.0, 0.0)),
        ({"roll": 1.4, "pitch": -0.8}, (1.0, -0.5)),
        ({"roll": 8.0, "pitch": -6.0}, (0.5, 0.5)),
    ]
    saved = (app.pitch_zero, app.roll_zero, app.corner_view)
    try:
        for values, (pitch_zero, roll_zero) in inputs:
            app.pitch_zero, app.roll_zero = pitch_zero, roll_zero
            _, pitch, roll = app.vehicle_values(values)
            heights = app.corner_lift_heights(values)
            app.corner_view = 0
            wedges = app.corner_page_content(values)
            ranked = sorted(heights.items(), key=lambda item: item[1], reverse=True)
            cases.append({
                "sensor": values,
                "zero": {"pitch": pitch_zero, "roll": roll_zero},
                "vehicle": {"pitch": round(pitch, 6), "roll": round(roll, 6)},
                "lift_cm": {
                    key: round(heights[corner], 6)
                    for key, corner in (
                        ("front_left", "FRONT LEFT"),
                        ("front_right", "FRONT RIGHT"),
                        ("rear_left", "REAR LEFT"),
                        ("rear_right", "REAR RIGHT"),
                    )
                },
                # The 2 WEDGES view: the two largest lifts, or level.
                "wedges": "LEVEL" if wedges == app.LEVEL_CONTENT else [
                    app.CORNER_TEXT_KEYS[corner] for corner, _ in ranked[:2]
                ],
                "van_tilt": {"rear": app.van_tilt(roll), "side": -app.van_tilt(pitch)},
            })
    finally:
        app.pitch_zero, app.roll_zero, app.corner_view = saved

    # Level frame hysteresis: (pitch, roll, was_level) -> is level now.
    hysteresis = [
        [pitch, roll, was_level, app.is_level(pitch, roll, was_level)]
        for pitch, roll in (
            (0.0, 0.0), (0.5, 0.0), (0.0, -0.5), (0.6, 0.0), (0.0, 0.7), (-0.7, 0.7), (0.71, 0.0),
        )
        for was_level in (False, True)
    ]
    return {
        "_comment": GENERATED_BY,
        "vehicle": {
            "wheelbase_mm": config.WHEELBASE_MM,
            "front_track_mm": config.FRONT_TRACK_MM,
            "rear_track_mm": config.REAR_TRACK_MM,
        },
        "axis_mapping": {
            "pitch_from": config.DISPLAY_PITCH_SENSOR_KEY,
            "pitch_sign": config.DISPLAY_PITCH_SIGN,
            "roll_from": config.DISPLAY_ROLL_SENSOR_KEY,
            "roll_sign": config.DISPLAY_ROLL_SIGN,
        },
        "cases": cases,
        "level_hysteresis": hysteresis,
    }


def outputs():
    return {
        "sensor.json": sensor_fixture(),
        "levelling.json": levelling_fixture(),
    }


def main(args):
    stale = []
    for name, data in outputs().items():
        path = TARGET / name
        text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        if "--check" in args:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
            continue
        TARGET.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("Wrote %s" % path.relative_to(ROOT.parent))
    if stale:
        print(
            "shared/fixtures/%s out of date; run esp32/tools/make_fixtures.py" % ", ".join(stale),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
